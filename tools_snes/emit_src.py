ARGQ = {0x0B: 0, 0x0D: 1, 0x0E: 2, 0x0F: 3}

def kvm_inc():
    L = ['; Koei bytecode VM (SNES Uncharted Waters) - one macro per opcode form', '; generated by tools_snes/emit_src.py', '']
    done = set()
    for o in sorted(OPS):
        nm, k, base = OPS[o]
        if nm in done: continue
        done.add(nm)
        if k == 'ql':   L += [f'.macro {nm} off', f'  .byte ${base:02X} + ((off) + $18) / 2', '.endmacro']
        elif k == 'qa': L += [f'.macro {nm} off', f'  .byte ${base:02X} + ((off) - $0B) / 2', '.endmacro']
        elif k == 'qi': L += [f'.macro {nm} n', f'  .byte ${base:02X} + (n)', '.endmacro']
        elif k in ('b',): L += [f'.macro {nm} v', f'  .byte ${o:02X}, <(v)', '.endmacro']
        elif k == 'ub':  L += [f'.macro {nm} v', f'  .byte ${o:02X}, v', '.endmacro']
        elif k in ('w', 'sw', 'lbl'): L += [f'.macro {nm} v', f'  .byte ${o:02X}', '  .word (v) & $FFFF', '.endmacro']
        elif k == 'rel': L += [f'.macro {nm} t', f'  .byte ${o:02X}, <((t) - * - 1)', '.endmacro']
        elif k is None: L += [f'.macro {nm}', f'  .byte ${o:02X}', '.endmacro']
    L += ['.macro k_callx f, n', '  .byte $E9', '  .word f', '  .byte n', '.endmacro',
          '; function prologue: JSR $21BA (enter VM) + frame size', '.macro k_func frame', '  .byte $20', '  .word $21BA', '  .word (-(frame)) & $FFFF', '.endmacro',
          '.macro k_switch base, n, dflt', '  .byte $D5', '  .word (base) & $FFFF, n, dflt', '.endmacro',
          '.macro k_switchn n', '  .byte $D9', '  .word n', '.endmacro',
          '.macro k_long sub', '  .byte $B7, sub', '.endmacro',
          '.macro k_longw sub, v', '  .byte $B7, sub', '  .word v', '.endmacro',
          '.macro k_longd sub, v', '  .byte $B7, sub', '  .dword v', '.endmacro']
    return '\n'.join(L) + '\n'

# ------------------------------------------------------------------ helpers
def hx(v, n): return f'${v:0{n}X}'

def data_lines(buf, start_pc, n, lab=None):
    """Emit raw bytes, printable runs as strings."""
    out = []; i = 0
    while i < n:
        j = i
        while j < n and 0x20 <= buf[j] < 0x7F and buf[j] != 0x22 and j - i < 48: j += 1
        if j - i >= 4:
            out.append(f'  .byte "{bytes(buf[i:j]).decode()}"'); i = j; continue
        k = i; run = []
        while k < n and len(run) < 16:
            if 0x20 <= buf[k] < 0x7F and buf[k] != 0x22:
                m = k
                while m < n and 0x20 <= buf[m] < 0x7F and buf[m] != 0x22: m += 1
                if m - k >= 4: break
            run.append(buf[k]); k += 1
        out.append('  .byte ' + ', '.join(hx(b, 2) for b in run)); i = k
    return out

NAT_FMT = {
    'imp': '{mn}', 'acc': '{mn} a', 'dp': '{mn} z:{v2}', 'dpx': '{mn} z:{v2},x', 'dpy': '{mn} z:{v2},y',
    'idp': '{mn} ({v2})', 'idpx': '{mn} ({v2},x)', 'idpy': '{mn} ({v2}),y', 'idl': '{mn} [{v2}]', 'idly': '{mn} [{v2}],y',
    'sr': '{mn} {v2},s', 'sry': '{mn} ({v2},s),y', 'abs': '{mn} a:{v4}', 'absx': '{mn} a:{v4},x', 'absy': '{mn} a:{v4},y',
    'ind': '{mn} ({v4})', 'indx': '{mn} ({v4},x)', 'indl': '{mn} [{v4}]', 'absl': '{mn} f:{v6}', 'abslx': '{mn} f:{v6},x',
}

def native_text(mn, md, val, pc, labels, nxt):
    mnl = mn.lower()
    if mn in ('BRK', 'COP', 'WDM'): return f'.byte ${ {"BRK":0,"COP":2,"WDM":0x42}[mn]:02X}, ${val:02X}'
    if md in ('immM', 'immX', 'imm8'):
        return f'{mnl} #{hx(val, 4 if val > 255 else 2)}' if md != 'imm8' else f'{mnl} #{hx(val, 2)}'
    if md == 'rel':
        t = (nxt + (val - 256 if val > 127 else val)) & 0xFFFF
        return f'{mnl} {labels.get(t, hx(t, 4))}'
    if md == 'rell':
        t = (nxt + (val - 65536 if val > 32767 else val)) & 0xFFFF
        return f'{mnl} {labels.get(t, hx(t, 4))}'
    if md == 'blk': return f'{mnl} #{hx(val >> 8, 2)},#{hx(val & 255, 2)}'
    if mn in ('JSR', 'JMP') and md == 'abs': return f'{mnl} {labels.get(val, hx(val, 4))}'
    if mn in ('JSL', 'JML') and md == 'absl': return f'{mnl} f:{labels.get(val, hx(val, 6))}'
    if mn == 'PEA': return f'pea {hx(val, 4)}'
    if mn == 'PEI': return f'pei ({hx(val, 2)})'
    if mn == 'PER':
        t = (nxt + (val - 65536 if val > 32767 else val)) & 0xFFFF
        return f'per {labels.get(t, hx(t, 4))}'
    if mn == 'JML' and md == 'indl': return f'jml [{hx(val, 4)}]'
    return NAT_FMT[md].format(mn=mnl, v2=hx(val, 2), v4=hx(val, 4), v6=hx(val, 6))

def bc_text(buf, off, pc, labels, ins_len):
    d = kinsn(buf, off, pc); op = buf[off]
    L = lambda a: labels.get(a, hx(a, 4))
    if op == 0xB7:
        sub = buf[off + 1]; n = B7LEN[sub]
        if n == 2: return [f'k_long ${sub:02X}']
        if n == 4: return [f'k_longw ${sub:02X}, {hx(buf[off+2] | buf[off+3] << 8, 4)}']
        return [f'k_longd ${sub:02X}, {hx(int.from_bytes(buf[off+2:off+6], "little"), 8)}']
    if op == 0xD5:
        base = buf[off + 1] | buf[off + 2] << 8; lim = buf[off + 3] | buf[off + 4] << 8; dflt = buf[off + 5] | buf[off + 6] << 8
        out = [f'k_switch {s16(base)}, {lim}, {L(dflt)}']
        tbl = [buf[off + 7 + 2 * i] | buf[off + 8 + 2 * i] << 8 for i in range(lim)]
        for i in range(0, lim, 8): out.append('  .word ' + ', '.join(L(t) for t in tbl[i:i + 8]))
        return out
    if op == 0xD9:
        n = buf[off + 1] | buf[off + 2] << 8
        out = [f'k_switchn {n}']
        for i in range(n):
            v = buf[off + 3 + 4 * i] | buf[off + 4 + 4 * i] << 8; t = buf[off + 5 + 4 * i] | buf[off + 6 + 4 * i] << 8
            out.append(f'  .word {hx(v, 4)}, {L(t)}')
        dflt = buf[off + 3 + 4 * n] | buf[off + 4 + 4 * n] << 8
        out.append(f'  .word {L(dflt)}')
        return out
    if op == 0xE9:
        return [f'k_callx {L(buf[off+1] | buf[off+2] << 8)}, {buf[off+3]}']
    nm, k, base = OPS[op]
    if k == 'ql': return [f'{nm} {-0x18 + 2 * (op - base)}']
    if k == 'qa': return [f'{nm} {0x0B + 2 * (op - base)}']
    if k == 'qi': return [f'{nm} {op - base}']
    if k == 'b': return [f'{nm} {s8(buf[off+1])}']
    if k == 'ub': return [f'{nm} {buf[off+1]}']
    v = buf[off + 1] | buf[off + 2] << 8
    if k == 'w': return [f'{nm} {hx(v, 4)}']
    if k == 'sw': return [f'{nm} {s16(v)}']
    if k == 'lbl': return [f'{nm} {L(v)}']
    if k == 'rel': return [f'{nm} {L(d["targets"][0])}']
    if k is None: return [nm]
    raise ValueError(op)

# ------------------------------------------------------------------ segment emitter
def emit_segment(name, start, size, off, ins, prefix, globals_=None, header=''):
    """ins: addr -> tuple from trace. Returns (text, labels)."""
    buf = ROM[off:off + size]
    # canonical instruction starts: walk sequentially, prefer recorded instructions
    starts = {}
    for a, t in ins.items():
        if start <= a < start + size: starts[a] = t
    # labels: targets of native/bytecode control flow and functions
    targets = set()
    for a, t in starts.items():
        n, kind = t[0], t[1]
        if kind == 'H': targets.add(a); continue
        if kind == 'B':
            d = kinsn(buf, a - start, a)
            for x in d['targets']: targets.add(x)
            if d['call'] is not None: targets.add(d['call'])
        elif kind == 'N':
            mn, md, val = t[2], t[3], t[4]
            nxt = (a + n) & 0xFFFF
            if md == 'rel': targets.add((nxt + (val - 256 if val > 127 else val)) & 0xFFFF)
            elif md == 'rell': targets.add((nxt + (val - 65536 if val > 32767 else val)) & 0xFFFF)
            elif mn in ('JSR', 'JMP') and md == 'abs': targets.add(val)
            elif mn == 'PER': targets.add((nxt + (val - 65536 if val > 32767 else val)) & 0xFFFF)
    labels = {}
    for a in targets:
        if start <= a < start + size and a in starts:
            k = starts[a][1]
            labels[a] = f'{prefix}{"F" if k == "H" else "L"}_{a:04X}'
    if globals_:
        for a, nm in globals_.items(): labels.setdefault(a, nm)
    lines = [header, '.p816', '.smart -', f'.include "kvm.inc"', '']
    if name != 'root' and globals_ is not None: lines.insert(4, '.include "root_syms.inc"')
    lines += ['.segment "CODE"', '']
    a = start; m16 = x16 = None; pend = []
    stats = defaultdict(int)
    def flush():
        nonlocal pend
        if pend:
            lines.extend(data_lines(bytes(pend), a - len(pend), len(pend))); stats['data'] += len(pend); pend = []
    while a < start + size:
        t = starts.get(a)
        # an instruction must fit and not overlap the next recorded start
        if t is None or a + t[0] > start + size:
            pend.append(buf[a - start]); a += 1; continue
        flush()
        if a in labels and not (globals_ and a in globals_ and name != 'root'):
            lines.append(f'{labels[a]}:')
        elif a in labels:
            lines.append(f'{labels[a]}:')
        n, kind = t[0], t[1]
        if kind == 'H':
            fr = buf[a - start + 3] | buf[a - start + 4] << 8
            lines.append(f'  k_func {(-s16(fr)) if fr else 0}'); stats['bc'] += 5
        elif kind == 'B':
            for l in bc_text(buf, a - start, a, labels, n): lines.append('  ' + l)
            stats['bc'] += n
        else:
            mn, md, val, m, x = t[2], t[3], t[4], t[5], t[6]
            if md == 'immM' and (not m) != m16: m16 = not m; lines.append('.a16' if m16 else '.a8')
            if md == 'immX' and (not x) != x16: x16 = not x; lines.append('.i16' if x16 else '.i8')
            lines.append('  ' + native_text(mn, md, val, a, labels, (a + n) & 0xFFFF)); stats['nat'] += n
        a += n
    flush()
    return '\n'.join(lines) + '\n', labels, stats

def rom_ins_bank0():
    """ROM native instructions in bank 0 keyed by CPU address."""
    ins = pickle.load(open(os.path.join(ROOT, 'out', 'trace_rom.pickle'), 'rb'))
    return {off + 0x8000: t for off, t in ins.items() if off < 0x8000}

def main():
    os.makedirs(os.path.join(SRC, 'ovl'), exist_ok=True)
    os.makedirs(os.path.join(ROOT, 'include'), exist_ok=True)
    open(os.path.join(ROOT, 'include', 'kvm.inc'), 'w').write(kvm_inc())
    ram = pickle.load(open(os.path.join(ROOT, 'out', 'trace_ram.pickle'), 'rb'))
    report = {}
    # bank 0
    txt, lab0, st = emit_segment('bank00', 0x8000, 0x8000, 0, rom_ins_bank0(), 'E', header='; Uncharted Waters (SNES US) - engine bank $00')
    open(os.path.join(SRC, 'bank00.s'), 'w').write(txt); report['bank00'] = dict(st)
    # root
    start, off, size, ins = ram['root']
    txt, labr, st = emit_segment('root', start, size, off, ins, 'R', header='; resident image, runs at $7E:2000')
    open(os.path.join(SRC, 'root.s'), 'w').write(txt); report['root'] = dict(st)
    syms = [f'{v} = ${k:04X}' for k, v in sorted(labr.items())]
    open(os.path.join(ROOT, 'include', 'root_syms.inc'), 'w').write('; root image symbols\n' + '\n'.join(syms) + '\n')
    for name, (start, off, size, ins) in ram.items():
        if name == 'root': continue
        txt, _, st = emit_segment(name, start, size, off, ins, name.upper() + '_', globals_=labr, header=f'; overlay {name}, runs at $7E:{start:04X}')
        open(os.path.join(SRC, 'ovl', f'{name}.s'), 'w').write(txt); report[name] = dict(st)
    json.dump(report, open(os.path.join(ROOT, 'out', 'emit_report.json'), 'w'), indent=1)
    for k, v in report.items(): print(k, v)

if __name__ == '__main__':
    main()
