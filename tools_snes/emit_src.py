"""Emit reassemblable ca65 source for Uncharted Waters (SNES US) from the trace.

  src/bank00.s          native engine ($00:8000-$FFFF): VM, syscalls, NMI/IRQ, file system, header
  src/root.s            resident image ($7E:2000): bytecode + native helpers + data
  src/ovl/<name>.s      overlays (run in $7E at their load base)
  include/kvm.inc       macros for the Koei bytecode VM (one macro per opcode form)
  include/root_syms.inc equates for root functions (used by the overlays)
Anything that is not code here (sgdata, fdata, cbmap0, kdata, graphics/sound banks)
is extracted from your own ROM by build.py into assets/ (never committed).
"""
