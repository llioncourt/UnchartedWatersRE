def emit_segment(name, start, size, off, ins, prefix, globals_=None, header='', dc=None, ext_syms=None):
    """ins: addr -> tuple from trace. dc: data classification of this module. Returns (text, labels)."""
    buf = ROM[off:off + size]
    blocks = {a: (n, k) for a, n, k in dc['blocks']} if dc else {}
    # canonical instruction starts: walk sequentially, prefer recorded instructions
    starts = {}
    for a, t in ins.items():
        if start <= a < start + size: starts[a] = t
    # labels: targets of native/bytecode control flow and functions
    targets = set()
    for a, t in starts.items():
        n, kind = t[0], t[1]
        if kind == 'H': targets.add(a); continue
        if kind == 'B':
            d = kinsn(buf, a - start, a)
            for x in d['targets']: targets.add(x)
            if d['call'] is not None: targets.add(d['call'])
        elif kind == 'N':
            mn, md, val = t[2], t[3], t[4]
            nxt = (a + n) & 0xFFFF
            if md == 'rel': targets.add((nxt + (val - 256 if val > 127 else val)) & 0xFFFF)
            elif md == 'rell': targets.add((nxt + (val - 65536 if val > 32767 else val)) & 0xFFFF)
            elif mn in ('JSR', 'JMP') and md == 'abs': targets.add(val)
            elif mn == 'PER': targets.add((nxt + (val - 65536 if val > 32767 else val)) & 0xFFFF)
    labels = {}
    for a in targets:
        if start <= a < start + size and a in starts:
            k = starts[a][1]
            labels[a] = f'{prefix}{"F" if k == "H" else "L"}_{a:04X}'
    for (mname, a), nm in NM.FUNCS.items():
        if mname == name and a in labels: labels[a] = nm
    if globals_:
        for a, nm in globals_.items():
            if not (start <= a < start + size) or a in starts: labels[a] = nm if (start <= a < start + size) else labels.get(a, nm)
    # data labels: referenced addresses and pointer-table targets that start a data block
    dlab = set(dc['refs']) if dc else set()
    for a, (n, k) in blocks.items():
        if k == 'P':
            for i in range(0, n, 2):
                w = buf[a - start + i] | buf[a - start + i + 1] << 8
                if start <= w < start + size and w not in starts: dlab.add(w)
    for a in dlab:
        if start <= a < start + size and a not in labels: labels[a] = f'{prefix}D_{a:04X}'
    syms = dict(labels)
    if ext_syms:
        for a, nm in ext_syms.items(): syms.setdefault(a, nm)
    lines = [header, '.p816', '.smart -', f'.include "kvm.inc"', '.include "ram.inc"', '']
    if name not in ('root', 'bank00') and globals_ is not None: lines.insert(5, '.include "root_syms.inc"')
    lines += ['.segment "CODE"', '']
    a = start; m16 = x16 = None; pend = []
    stats = defaultdict(int)
    def flush():
        nonlocal pend
        if pend:
            lines.extend(data_lines(bytes(pend), a - len(pend), len(pend))); stats['data'] += len(pend); pend = []
    def label_here(x):
        if x in labels: lines.append(f'{labels[x]}:')
    while a < start + size:
        t = starts.get(a)
        # an instruction must fit and not overlap the next recorded start
        if t is None or a + t[0] > start + size:
            if a in blocks and not pend:
                n, k = blocks[a]
                # a data block may contain inner labels: split at them
                cuts = [x for x in range(a + 1, a + n) if x in labels]
                pos = a
                for c in cuts + [a + n]:
                    label_here(pos)
                    lines.extend(data_block(buf, start, pos, c - pos, k, syms)); stats[k] += c - pos
                    pos = c
                a += n; continue
            pend.append(buf[a - start]); a += 1; continue
        flush()
        label_here(a)
        n, kind = t[0], t[1]
        if kind == 'H':
            fr = buf[a - start + 3] | buf[a - start + 4] << 8
            lines.append(f'  k_func {(-s16(fr)) if fr else 0}'); stats['bc'] += 5
        elif kind == 'B':
            for l in bc_text(buf, a - start, a, labels, n, syms): lines.append('  ' + l)
            stats['bc'] += n
        else:
            mn, md, val, m, x = t[2], t[3], t[4], t[5], t[6]
            if md == 'immM' and (not m) != m16: m16 = not m; lines.append('.a16' if m16 else '.a8')
            if md == 'immX' and (not x) != x16: x16 = not x; lines.append('.i16' if x16 else '.i8')
            lines.append('  ' + native_text(mn, md, val, a, labels, (a + n) & 0xFFFF, syms)); stats['nat'] += n
        a += n
    flush()
    return '\n'.join(annotate(lines, labels, prefix)) + '\n', labels, stats

VMNAMES = {}
def annotate(lines, labels, prefix):
    """Comments: syscall name on each syscall call; a summary line above each bytecode function."""
    import re
    out = []
    for i, l in enumerate(lines):
        m = re.match(r'  k_callx (syscall|RL_21BE), (\d+)$', l)
        if m and i and re.match(r'  k_pushib? (\d+)$', lines[i - 1]):
            n = int(lines[i - 1].split()[-1])
            nm = NM.SYS.get(n, ('',))[0]
            l = f'{l}  ; sys {n} {nm}'.rstrip()
        out.append(l)
    # function summaries
    func_re = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*):$')
    starts = [i for i, l in enumerate(out) if func_re.match(l) and i + 1 < len(out) and out[i + 1].startswith('  k_func')]
    res = []; si = set(starts)
    bounds = starts + [len(out)]
    summ = {}
    for j, st in enumerate(starts):
        body = out[st:bounds[j + 1]]
        sysn, ram, calls, strs = [], [], [], []
        for b in body:
            m = re.search(r'; sys (\d+) (\w+)', b)
            if m and m.group(2) not in sysn: sysn.append(m.group(2))
            for r in re.findall(r'\b(g_[a-z_0-9]+)', b):
                if r not in ram: ram.append(r)
            m = re.match(r'  k_call(?:x)? ([A-Za-z_][A-Za-z0-9_]*)', b)
            if m and m.group(1) not in ('syscall', 'RL_21BE') and m.group(1) not in calls: calls.append(m.group(1))
        parts = []
        if sysn: parts.append('sys: ' + ', '.join(sysn[:6]))
        if ram: parts.append('vars: ' + ', '.join(ram[:6]))
        if calls: parts.append(f'calls {len(calls)}')
        if parts: summ[st] = '; ' + ' | '.join(parts)
    for i, l in enumerate(out):
        if i in summ: res.append(summ[i])
        res.append(l)
    return res

def table_labels():
    """Names for handlers reached only through the engine's jump tables."""
    from kbc import NAMES as KN
    lab = {}
    w = lambda o: ROM[o] | ROM[o + 1] << 8
    for i in range(79):
        nm = NM.SYS.get(i, ('',))[0]
        lab.setdefault(w(0x19F0 + 2 * i), f'sys_{i:02d}' + (f'_{nm}' if nm else ''))
    for a, nm in NM.BANK0.items(): lab.setdefault(a, nm)
    for op in range(256):
        a = w(0x2797 + 2 * op)
        if a < 0x8000: continue
        nm = KN.get(op, f'op{op:02X}').split()[0].lower().replace('?', '').replace('+', 'x')
        lab.setdefault(a, f'vm_{op:02X}_{nm}')
    for sub in range(1, 0x30):
        a = w(0x29AF + 2 * sub)
        if a >= 0x8000: lab.setdefault(a, f'vm_b7_{sub:02X}')
    lab[0x800F] = 'reset'; lab[w(0x7FEA)] = 'nmi'; lab[w(0x7FEE)] = 'irq'
    lab[0xA0FD] = 'vm_enter'; lab[0xA0D9] = 'syscall_gate'; lab[0x8DDD] = 'syscall_dispatch'
    lab[0xA141] = 'vm_fetch'; lab[0xA997] = 'vm_b7_prefix'
    return lab

def rom_ins_bank0():
    """ROM native instructions in bank 0 keyed by CPU address."""
    ins = pickle.load(open(os.path.join(ROOT, 'out', 'trace_rom.pickle'), 'rb'))
    return {off + 0x8000: t for off, t in ins.items() if off < 0x8000}

