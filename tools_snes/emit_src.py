def ram_name(v, exact=False):
    r = NM.ram_symbol(v) if v >= 0xDF00 else (NM.ram_symbol(v, True) if v < 0x2000 else None)
    if r and exact and '+' in r: return None
    return r

def data_block(buf, start, a, n, k, syms):
    b = buf[a - start:a - start + n]
    if k == 'Z':
        return [f'  .res {n}, ${b[0]:02X}']
    if k == 'C' and n % 2 == 0:
        ws = [b[i] | b[i + 1] << 8 for i in range(0, n, 2)]
        return ['  .word ' + ', '.join(hx(w, 4) for w in ws[i:i + 8]) + '  ; BGR555' for i in range(0, len(ws), 8)]
    if k == 'F' and n % 16 == 0:
        out = ['  ; file directory: name[8], bank, 0, address, size, 0']
        for i in range(0, n, 16):
            e = b[i:i + 16]
            if e[0] == 0 and not any(e):
                out.append(f'  .res {n - i}, $00'); break
            nm = e[:8].split(bytes([0]))[0].decode('ascii')
            out.append(f'  .byte "{nm}"' + ', $00' * (8 - len(nm)) + f', ${e[8]:02X}, ${e[9]:02X}')
            out.append(f'  .word ${e[10] | e[11] << 8:04X}, ${e[12] | e[13] << 8:04X}, ${e[14] | e[15] << 8:04X}')
        return out
    if k == 'P' and n % 2 == 0:
        ws = [b[i] | b[i + 1] << 8 for i in range(0, n, 2)]
        return ['  .word ' + ', '.join(syms.get(w, hx(w, 4)) for w in ws[i:i + 8]) for i in range(0, len(ws), 8)]
    if k == 'S':
        parts = []; cur = ''
        for c in b:
            if 0x20 <= c < 0x7F and c != 0x22:
                cur += chr(c)
            else:
                if cur: parts.append(f'"{cur}"'); cur = ''
                parts.append(hx(c, 2))
        if cur: parts.append(f'"{cur}"')
        out = []; line = []
        for p in parts:
            line.append(p)
            if sum(len(x) for x in line) > 70: out.append('  .byte ' + ', '.join(line)); line = []
        if line: out.append('  .byte ' + ', '.join(line))
        return out
    return data_lines(b, a, n)

def native_text(mn, md, val, pc, labels, nxt, syms=None):
    mnl = mn.lower()
    if mn in ('BRK', 'COP', 'WDM'): return f'.byte ${ {"BRK":0,"COP":2,"WDM":0x42}[mn]:02X}, ${val:02X}'
    if syms and md in ('abs', 'absx', 'absy') and mn not in ('JSR', 'JMP') and val in syms:
        return NAT_FMT[md].replace('{v4}', syms[val]).format(mn=mnl, v2='', v4='', v6='')
    if md in ('abs', 'absx', 'absy') and mn not in ('JSR', 'JMP') and ram_name(val):
        return NAT_FMT[md].replace('{v4}', ram_name(val)).format(mn=mnl, v2='', v4='', v6='')
    if syms and md in ('immM', 'immX') and mn in ('LDA', 'LDX', 'LDY') and val is not None and val > 0xFF and val in syms:
        return f'{mnl} #{syms[val]}'
    if md in ('immM', 'immX', 'imm8'):
        return f'{mnl} #{hx(val, 4 if val > 255 else 2)}' if md != 'imm8' else f'{mnl} #{hx(val, 2)}'
    if md == 'rel':
        t = (nxt + (val - 256 if val > 127 else val)) & 0xFFFF
        return f'{mnl} {labels.get(t, hx(t, 4))}'
    if md == 'rell':
        t = (nxt + (val - 65536 if val > 32767 else val)) & 0xFFFF
        return f'{mnl} {labels.get(t, hx(t, 4))}'
    if md == 'blk': return f'{mnl} #{hx(val >> 8, 2)},#{hx(val & 255, 2)}'
    if mn in ('JSR', 'JMP') and md == 'abs': return f'{mnl} {labels.get(val, hx(val, 4))}'
    if mn in ('JSL', 'JML') and md == 'absl': return f'{mnl} f:{labels.get(val, hx(val, 6))}'
    if mn == 'PEA': return f'pea {hx(val, 4)}'
    if mn == 'PEI': return f'pei ({hx(val, 2)})'
    if mn == 'PER':
        t = (nxt + (val - 65536 if val > 32767 else val)) & 0xFFFF
        return f'per {labels.get(t, hx(t, 4))}'
    if mn == 'JML' and md == 'indl': return f'jml [{hx(val, 4)}]'
    return NAT_FMT[md].format(mn=mnl, v2=hx(val, 2), v4=hx(val, 4), v6=hx(val, 6))

def bc_text(buf, off, pc, labels, ins_len, syms=None):
    d = kinsn(buf, off, pc); op = buf[off]
    L = lambda a: labels.get(a, hx(a, 4))
    if op == 0xB7:
        sub = buf[off + 1]; n = B7LEN[sub]
        if n == 2: return [f'k_long ${sub:02X}']
        if n == 4: return [f'k_longw ${sub:02X}, {hx(buf[off+2] | buf[off+3] << 8, 4)}']
        return [f'k_longd ${sub:02X}, {hx(int.from_bytes(buf[off+2:off+6], "little"), 8)}']
    if op == 0xD5:
        base = buf[off + 1] | buf[off + 2] << 8; lim = buf[off + 3] | buf[off + 4] << 8; dflt = buf[off + 5] | buf[off + 6] << 8
        out = [f'k_switch {s16(base)}, {lim}, {L(dflt)}']
        tbl = [buf[off + 7 + 2 * i] | buf[off + 8 + 2 * i] << 8 for i in range(lim)]
        for i in range(0, lim, 8): out.append('  .word ' + ', '.join(L(t) for t in tbl[i:i + 8]))
        return out
    if op == 0xD9:
        n = buf[off + 1] | buf[off + 2] << 8
        out = [f'k_switchn {n}']
        for i in range(n):
            v = buf[off + 3 + 4 * i] | buf[off + 4 + 4 * i] << 8; t = buf[off + 5 + 4 * i] | buf[off + 6 + 4 * i] << 8
            out.append(f'  .word {hx(v, 4)}, {L(t)}')
        dflt = buf[off + 3 + 4 * n] | buf[off + 4 + 4 * n] << 8
        out.append(f'  .word {L(dflt)}')
        return out
    if op == 0xE9:
        return [f'k_callx {L(buf[off+1] | buf[off+2] << 8)}, {buf[off+3]}']
    nm, k, base = OPS[op]
    if k == 'ql': return [f'{nm} {-0x18 + 2 * (op - base)}']
    if k == 'qa': return [f'{nm} {0x0B + 2 * (op - base)}']
    if k == 'qi': return [f'{nm} {op - base}']
    if k == 'b': return [f'{nm} {s8(buf[off+1])}']
    if k == 'ub': return [f'{nm} {buf[off+1]}']
    v = buf[off + 1] | buf[off + 2] << 8
    if k == 'w':
        if syms and op in SYM_OPS and v in syms: return [f'{nm} {syms[v]}']
        if op in SYM_OPS:
            r = ram_name(v, exact=op not in MEM_OPS)
            if r: return [f'{nm} {r}']
        return [f'{nm} {hx(v, 4)}']
    if k == 'sw': return [f'{nm} {s16(v)}']
    if k == 'lbl': return [f'{nm} {L(v)}']
    if k == 'rel': return [f'{nm} {L(d["targets"][0])}']
    if k is None: return [nm]
    raise ValueError(op)

